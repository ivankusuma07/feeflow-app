// Exports ABIs from Foundry artifacts into src/generated.ts (committed).
// Run after `forge build` in contracts/: `pnpm --filter @feeflow/abi generate`.
// CI regenerates and fails on diff, so the committed ABI always matches the contracts.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const out = join(root, "contracts", "out");

const ARTIFACTS = [
  ["feeFlowAbi", "FeeFlow.sol/FeeFlow.json"],
  ["feeSinkAbi", "FeeSink.sol/FeeSink.json"],
  // Pons interfaces transcribed from the Pons docs; Stage 0 replaces them with verified ABIs.
  ["ponsFactoryAbi", "IPons.sol/IPonsFactory.json"],
  ["ponsFeeEscrowAbi", "IPons.sol/IPonsFeeEscrow.json"],
];

let src = "// GENERATED by packages/abi/scripts/export.mjs from contracts/out. Do not edit.\n\n";
for (const [name, path] of ARTIFACTS) {
  const artifact = JSON.parse(await readFile(join(out, path), "utf8"));
  src += `export const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
await writeFile(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "generated.ts"), src);
console.log(`wrote ${ARTIFACTS.length} ABIs`);
